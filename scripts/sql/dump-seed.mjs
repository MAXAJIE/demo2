#!/usr/bin/env node
/**
 * Generate supabase/migrations/0005_seed.sql from the current demo database.
 *
 * Inputs (read only):
 *   backend/data/coresite.db          - structure, ids, ordering, settings scalars
 *   content/setapak.bundle.json       - the public bundle, which already has the
 *                                       Malay (and Chinese) strings filled in
 *
 * Why two sources: the SQL layer does not translate at read time, so every i18n
 * payload in the seed must already carry en/ms/zh. The API bundle is the one
 * place that transformation has happened, so it is used for the JSON columns.
 *
 * Re-run whenever the demo content changes:
 *   node scripts/dump-bundle.mjs && node scripts/sql/dump-seed.mjs
 */
import { DatabaseSync } from "node:sqlite";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..", "..");
const dbPath = resolve(root, "backend", "data", "coresite.db");
const bundlePath = resolve(root, "content", "setapak.bundle.json");
const outPath = resolve(root, "supabase", "migrations", "0005_seed.sql");

const db = new DatabaseSync(dbPath, { readOnly: true });
const bundle = JSON.parse(readFileSync(bundlePath, "utf8"));

const text = (value) =>
  value === null || value === undefined ? "null" : `'${String(value).replace(/'/g, "''")}'`;
const json = (value) =>
  value === null || value === undefined ? "null" : `${text(JSON.stringify(value))}::jsonb`;
const bool = (value) => (value ? "true" : "false");
const num = (value) => (value === null || value === undefined ? "null" : String(value));
// SQLite stores JSON columns as text; parse before passing to json() so the value
// is embedded once, not as a JSON string inside a JSON string.
const parseJsonColumn = (value) => {
  if (value === null || value === undefined) return null;
  if (typeof value !== "string") return value;
  try {
    return JSON.parse(value);
  } catch {
    return value;
  }
};

const pickContent = (page, section) => bundle.content?.[page]?.[section] ?? null;
const offeringById = new Map((bundle.offerings ?? []).map((item) => [item.id, item]));
const faqById = new Map((bundle.faq ?? []).map((item) => [item.id, item]));

const tenants = db.prepare("select * from tenants order by id").all();
const domains = db.prepare("select * from tenant_domains order by hostname").all();
const settings = db.prepare("select * from site_settings").all();
const pages = db.prepare("select * from page_content order by page, section").all();
const offerings = db.prepare("select * from offerings order by sort, slug").all();
const faq = db.prepare("select * from faq_items order by sort").all();
const rules = db.prepare("select * from availability_rules order by weekday, start_time").all();
const blackouts = db.prepare("select * from blackout_dates order by date_from").all();

const lines = [];
lines.push("-- 0005_seed.sql — generated by scripts/sql/dump-seed.mjs; do not hand-edit.");
lines.push(`-- Source: backend/data/coresite.db + content/setapak.bundle.json`);
lines.push(`-- Tenant: ${bundle.tenant?.slug ?? "unknown"}`);
lines.push("--");
lines.push("-- i18n payloads already contain en/ms/zh (the bundle is dumped through the API,");
lines.push("-- which fills Malay). Locales are forced to all three by owner decision.");
lines.push("-- Log a new client in only after creating their account in Supabase Auth:");
lines.push("--   insert into public.platform_admins (user_id) values ('<your-auth-user-uuid>');");
lines.push("");
lines.push("begin;");

for (const tenant of tenants) {
  lines.push(
    `insert into public.tenants (id, slug, status, plan) values (${text(tenant.id)}, ${text(
      tenant.slug,
    )}, ${text(tenant.status)}, ${text(tenant.plan)}) on conflict (id) do nothing;`,
  );
}

for (const domain of domains) {
  lines.push(
    `insert into public.tenant_domains (hostname, tenant_id, is_primary) values (${text(
      domain.hostname,
    )}, ${text(domain.tenant_id)}, ${bool(domain.is_primary)}) on conflict (hostname) do nothing;`,
  );
}

for (const row of settings) {
  const site = bundle.site ?? {};
  const theme = parseJsonColumn(row.theme);
  const features = parseJsonColumn(row.features) ?? site.features ?? {};
  const paymentConfig = parseJsonColumn(row.payment_config) ?? {};
  const analytics = parseJsonColumn(row.analytics) ?? {};
  lines.push(
    `insert into public.site_settings (
  tenant_id, brand_name, preset_key, archetype, default_locale, locales, timezone, theme,
  features, labels, contact, booking_mode, reminder_hours, checkout_mode, payment_config,
  analytics, consent_text
) values (
  ${text(row.tenant_id)}, ${json(site.brand_name)}, ${text(row.preset_key)}, ${text(
      row.archetype,
    )}, ${text(row.default_locale)}, '["en","ms","zh"]'::jsonb, ${text(row.timezone)},
  ${json(theme)}, ${json(features)}, ${json(site.labels)},
  ${json(site.contact)}, ${text(row.booking_mode)}, ${num(row.reminder_hours)},
  ${text(row.checkout_mode)}, ${json(paymentConfig)}, ${json(analytics)},
  ${json(site.consent_text)}
) on conflict (tenant_id) do nothing;`,
  );
}

for (const row of pages) {
  const data = pickContent(row.page, row.section);
  if (data === null) continue;
  lines.push(
    `insert into public.page_content (id, tenant_id, page, section, data, sort) values (${text(
      row.id,
    )}, ${text(row.tenant_id)}, ${text(row.page)}, ${text(row.section)}, ${json(
      data,
    )}, ${num(row.sort)}) on conflict (tenant_id, page, section) do nothing;`,
  );
}

for (const row of offerings) {
  const fromBundle = offeringById.get(row.id);
  const title = fromBundle?.title ?? JSON.parse(row.title);
  const summary = fromBundle?.summary ?? JSON.parse(row.summary);
  const body = fromBundle?.body ?? JSON.parse(row.body);
  const priceNote = fromBundle?.price_note ?? JSON.parse(row.price_note);
  lines.push(
    `insert into public.offerings (
  id, tenant_id, slug, kind, title, summary, body, price_cents, deposit_cents, currency,
  price_note, checkout_url, image_media_ids, attributes, status, sort, seo
) values (
  ${text(row.id)}, ${text(row.tenant_id)}, ${text(row.slug)}, ${text(row.kind)},
  ${json(title)}, ${json(summary)}, ${json(body)},
  ${num(row.price_cents)}, ${num(row.deposit_cents)}, ${text(row.currency)},
  ${json(priceNote)}, ${text(row.checkout_url)}, ${json(JSON.parse(row.image_media_ids || "[]"))},
  ${json(fromBundle?.attributes ?? JSON.parse(row.attributes))}, ${text(row.status)},
  ${num(row.sort)}, ${json(JSON.parse(row.seo || "{}"))}
) on conflict (id) do nothing;`,
  );
}

for (const row of faq) {
  const fromBundle = faqById.get(row.id);
  if (!fromBundle) continue;
  lines.push(
    `insert into public.faq_items (id, tenant_id, offering_id, question, answer, sort, published)
values (${text(row.id)}, ${text(row.tenant_id)}, ${text(row.offering_id)}, ${json(
      fromBundle.question,
    )}, ${json(fromBundle.answer)}, ${num(row.sort)}, ${bool(row.published)})
on conflict (id) do nothing;`,
  );
}

for (const row of rules) {
  lines.push(
    `insert into public.availability_rules (id, tenant_id, offering_id, weekday, start_time, end_time, slot_minutes, buffer_minutes, active)
values (${text(row.id)}, ${text(row.tenant_id)}, ${text(row.offering_id)}, ${num(
      row.weekday,
    )}, ${text(row.start_time)}, ${text(row.end_time)}, ${num(row.slot_minutes)}, 0, ${bool(
      row.active,
    )}) on conflict (id) do nothing;`,
  );
}

for (const row of blackouts) {
  lines.push(
    `insert into public.blackout_dates (id, tenant_id, date_from, date_to, reason)
values (${text(row.id)}, ${text(row.tenant_id)}, ${text(row.date_from)}, ${text(
      row.date_to,
    )}, ${text(row.reason)}) on conflict (id) do nothing;`,
  );
}

lines.push("commit;");
lines.push("");

writeFileSync(outPath, `${lines.join("\n")}`, "utf8");
console.log(
  `Wrote ${outPath}\n  tenants=${tenants.length} domains=${domains.length} settings=${settings.length} pages=${pages.length} offerings=${offerings.length} faq=${faq.length} rules=${rules.length} blackouts=${blackouts.length}`,
);
